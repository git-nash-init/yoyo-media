// Pure ingest rules: no prisma, no server-only, no fs. Unit-tested in tests/ingest.test.ts.
import { z } from "zod";

/** Chunk size Studio is told to use. Every request stays far below the 120 s host limit. */
export const CHUNK_SIZE = 5 * 1024 * 1024;
/** Hard cap on a single PUT body. */
export const MAX_CHUNK_BYTES = 8 * 1024 * 1024;
/** Unfinished uploads older than this are deleted when the same token starts a new upload. */
export const STALE_UPLOAD_MS = 24 * 60 * 60 * 1000;
/** Finished uploads never attached to a video are deleted after this long. */
export const ORPHAN_UPLOAD_MS = 7 * 24 * 60 * 60 * 1000;

export const TOKEN_PREFIX = "yoyo_ing_";

export const INGEST_KINDS = ["video", "rendition", "preview", "thumb"] as const;
export type IngestKind = (typeof INGEST_KINDS)[number];

export type KindRule = {
  exts: readonly string[];
  group: "video" | "image";
  folder: "videos" | "previews" | "thumbs";
};

export const KIND_RULES: Record<IngestKind, KindRule> = {
  video: { exts: ["mp4", "webm"], group: "video", folder: "videos" },
  // A lower-quality copy of the main video (480p, 360p ...).
  rendition: { exts: ["mp4", "webm"], group: "video", folder: "videos" },
  preview: { exts: ["mp4", "webm"], group: "video", folder: "previews" },
  thumb: { exts: ["jpg", "jpeg", "png", "webp"], group: "image", folder: "thumbs" },
};

export const isIngestKind = (v: unknown): v is IngestKind =>
  typeof v === "string" && (INGEST_KINDS as readonly string[]).includes(v);

export type RuleError = { ok: false; status: number; code: string; error: string };
export type RuleOk = { ok: true };
const fail = (status: number, code: string, error: string): RuleError => ({ ok: false, status, code, error });

/** Lower-cased extension without the dot ("" when there is none). */
export function extOf(filename: string): string {
  const base = filename.split(/[\\/]/).pop() ?? "";
  const i = base.lastIndexOf(".");
  return i <= 0 || i === base.length - 1 ? "" : base.slice(i + 1).toLowerCase();
}

export const createUploadSchema = z.object({
  kind: z.enum(INGEST_KINDS),
  // Stored in the database for reference only; it is never used as a path on disk.
  filename: z
    .string()
    .trim()
    .min(1)
    .max(191)
    .refine((s) => !/[\u0000-\u001f]/.test(s), "Invalid filename"),
  totalSize: z.number().int().positive().max(Number.MAX_SAFE_INTEGER),
  sha256: z
    .string()
    .regex(/^[a-fA-F0-9]{64}$/, "sha256 must be 64 hex characters")
    .transform((s) => s.toLowerCase()),
});
export type CreateUploadInput = z.infer<typeof createUploadSchema>;

export type SizeLimits = { maxVideoBytes: number; maxImageBytes: number };

export function maxBytesFor(kind: IngestKind, limits: SizeLimits): number {
  return KIND_RULES[kind].group === "image" ? limits.maxImageBytes : limits.maxVideoBytes;
}

/** Extension allow-list and size cap for a new upload. */
export function checkUploadRequest(
  input: Pick<CreateUploadInput, "kind" | "filename" | "totalSize">,
  limits: SizeLimits,
): RuleOk | RuleError {
  const rule = KIND_RULES[input.kind];
  const ext = extOf(input.filename);
  if (!rule.exts.includes(ext))
    return fail(415, "BAD_EXTENSION", `A ${input.kind} file must be one of: ${rule.exts.join(", ")}`);
  const max = maxBytesFor(input.kind, limits);
  if (input.totalSize > max) return fail(413, "TOO_LARGE", `A ${input.kind} file may be at most ${max} bytes`);
  return { ok: true };
}

/** Does the sniffed magic-byte type match what the upload declared? */
export function sniffMatchesKind(kind: IngestKind, sniffed: { group: "image" | "video" } | null): boolean {
  return !!sniffed && sniffed.group === KIND_RULES[kind].group;
}

/** Parse the `offset` query parameter: a plain non-negative integer or null. */
export function parseOffset(raw: string | null): number | null {
  if (raw == null || !/^\d{1,16}$/.test(raw)) return null;
  const n = Number(raw);
  return Number.isSafeInteger(n) ? n : null;
}

/** Validate one chunk against the upload's current position. */
export function checkChunk(p: {
  offset: number;
  received: number;
  totalSize: number;
  chunkLength: number;
}): RuleOk | RuleError {
  if (p.chunkLength <= 0) return fail(400, "EMPTY_CHUNK", "The chunk is empty");
  if (p.chunkLength > MAX_CHUNK_BYTES)
    return fail(413, "CHUNK_TOO_LARGE", `A chunk may be at most ${MAX_CHUNK_BYTES} bytes`);
  if (p.offset !== p.received) return fail(409, "OFFSET_MISMATCH", "Offset does not match the bytes received so far");
  if (p.offset + p.chunkLength > p.totalSize)
    return fail(413, "EXCEEDS_TOTAL", "The chunk would exceed the declared total size");
  return { ok: true };
}

/** Upload ids are cuids generated by the database layer. */
export const isUploadId = (v: unknown): v is string => typeof v === "string" && /^[a-z0-9]{8,40}$/.test(v);

const uploadId = z.string().regex(/^[a-z0-9]{8,40}$/, "Invalid upload id");

/** One lower-quality copy: its short side in pixels and the upload that carries it. */
export const renditionRefSchema = z.object({
  height: z.number().int().min(144).max(2160),
  uploadId,
});
export type RenditionRef = z.infer<typeof renditionRefSchema>;

export const createVideoSchema = z
  .object({
    title: z.string().trim().min(1).max(150),
    type: z.enum(["LONG", "SHORT"]),
    durationSec: z
      .number()
      .int()
      .min(0)
      .max(24 * 60 * 60),
    description: z.string().trim().max(5000).optional(),
    videoUploadId: uploadId,
    previewUploadId: uploadId.optional(),
    thumbUploadIds: z.array(uploadId).max(5).default([]),
    /** Short side of the main video in pixels (720 for a 720p file). */
    heightPx: z.number().int().min(0).max(4320).default(0),
    renditions: z.array(renditionRefSchema).max(6).default([]),
  })
  .refine(
    (v) => {
      const ids = [
        v.videoUploadId,
        ...(v.previewUploadId ? [v.previewUploadId] : []),
        ...v.thumbUploadIds,
        ...v.renditions.map((r) => r.uploadId),
      ];
      return new Set(ids).size === ids.length;
    },
    { message: "Each upload may be referenced only once", path: ["thumbUploadIds"] },
  )
  .refine((v) => new Set(v.renditions.map((r) => r.height)).size === v.renditions.length, {
    message: "Each quality may be given only once",
    path: ["renditions"],
  });
export type CreateVideoInput = z.infer<typeof createVideoSchema>;

/** Add lower qualities to a video that already exists (Studio's backfill). */
export const attachRenditionsSchema = z
  .object({
    heightPx: z.number().int().min(0).max(4320).default(0),
    renditions: z.array(renditionRefSchema).min(1).max(6),
  })
  .refine((v) => new Set(v.renditions.map((r) => r.height)).size === v.renditions.length, {
    message: "Each quality may be given only once",
    path: ["renditions"],
  })
  .refine((v) => new Set(v.renditions.map((r) => r.uploadId)).size === v.renditions.length, {
    message: "Each upload may be referenced only once",
    path: ["renditions"],
  });
export type AttachRenditionsInput = z.infer<typeof attachRenditionsSchema>;

export type UploadRef = { id: string; tokenId: string; kind: string; status: string; finalPath: string | null };

/**
 * Every referenced upload must exist, belong to this token, be COMPLETE (not yet
 * CONSUMED) and be of the kind its slot expects.
 */
export function checkVideoUploads(
  input: Pick<CreateVideoInput, "videoUploadId" | "previewUploadId" | "thumbUploadIds"> & { renditions?: RenditionRef[] },
  uploads: UploadRef[],
  tokenId: string,
): RuleOk | RuleError {
  const byId = new Map(uploads.map((u) => [u.id, u]));
  const wanted: [string, IngestKind][] = [
    [input.videoUploadId, "video"],
    ...(input.previewUploadId ? ([[input.previewUploadId, "preview"]] as [string, IngestKind][]) : []),
    ...input.thumbUploadIds.map((id) => [id, "thumb"] as [string, IngestKind]),
    ...(input.renditions ?? []).map((r) => [r.uploadId, "rendition"] as [string, IngestKind]),
  ];
  for (const [id, kind] of wanted) {
    const u = byId.get(id);
    // Another token's upload looks exactly like a missing one.
    if (!u || u.tokenId !== tokenId) return fail(404, "UPLOAD_NOT_FOUND", `Upload ${id} was not found`);
    if (u.kind !== kind) return fail(422, "WRONG_KIND", `Upload ${id} is a ${u.kind}, expected a ${kind}`);
    if (u.status === "CONSUMED") return fail(409, "UPLOAD_CONSUMED", `Upload ${id} was already used for a video`);
    if (u.status !== "COMPLETE" || !u.finalPath)
      return fail(409, "UPLOAD_INCOMPLETE", `Upload ${id} is not complete yet`);
  }
  return { ok: true };
}

/** Same ownership and state checks for the uploads that carry extra qualities. */
export function checkRenditionUploads(renditions: RenditionRef[], uploads: UploadRef[], tokenId: string): RuleOk | RuleError {
  const byId = new Map(uploads.map((u) => [u.id, u]));
  for (const r of renditions) {
    const u = byId.get(r.uploadId);
    if (!u || u.tokenId !== tokenId) return fail(404, "UPLOAD_NOT_FOUND", `Upload ${r.uploadId} was not found`);
    if (u.kind !== "rendition") return fail(422, "WRONG_KIND", `Upload ${r.uploadId} is a ${u.kind}, expected a rendition`);
    if (u.status === "CONSUMED") return fail(409, "UPLOAD_CONSUMED", `Upload ${r.uploadId} was already used`);
    if (u.status !== "COMPLETE" || !u.finalPath)
      return fail(409, "UPLOAD_INCOMPLETE", `Upload ${r.uploadId} is not complete yet`);
  }
  return { ok: true };
}

/**
 * Return `base` if free, otherwise `base-<suffix>` with a short random suffix.
 * `exists` and `rand` are injected so this stays pure and testable.
 */
export async function pickUniqueSlug(
  base: string,
  exists: (slug: string) => Promise<boolean>,
  rand: () => string,
  maxTries = 6,
): Promise<string> {
  if (!(await exists(base))) return base;
  for (let i = 0; i < maxTries; i++) {
    const candidate = withSlugSuffix(base, rand());
    if (!(await exists(candidate))) return candidate;
  }
  throw new Error("Could not find a free slug");
}

export function withSlugSuffix(base: string, suffix: string): string {
  const clean = suffix.toLowerCase().replace(/[^a-z0-9]/g, "").slice(0, 8) || "x";
  return `${base.slice(0, 80).replace(/-+$/, "")}-${clean}`;
}

/** Extract the bearer token; null unless it looks like an ingest token. */
export function tokenFromAuthHeader(header: string | null | undefined): string | null {
  if (!header) return null;
  const m = /^Bearer\s+(\S+)\s*$/i.exec(header);
  if (!m) return null;
  const token = m[1];
  if (!token.startsWith(TOKEN_PREFIX) || token.length < TOKEN_PREFIX.length + 20 || token.length > 200) return null;
  return token;
}
